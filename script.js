const storageKey = "portfolio-language";
const languageToggle = document.querySelector("#language-toggle");

function readSavedLanguage() {
  try {
    const savedLanguage = window.localStorage.getItem(storageKey);
    return savedLanguage === "en" ? "en" : "zh";
  } catch {
    return "zh";
  }
}

function saveLanguage(language) {
  try {
    window.localStorage.setItem(storageKey, language);
  } catch {
    // The page still works when storage is unavailable, such as some file:// contexts.
  }
}

function applyLanguage(language) {
  const copy = translations[language];

  document.documentElement.lang = language === "zh" ? "zh-CN" : "en";
  document.documentElement.dataset.language = language;
  document.title = copy.metaTitle;

  const description = document.querySelector('meta[name="description"]');
  const openGraphTitle = document.querySelector('meta[property="og:title"]');
  const openGraphDescription = document.querySelector('meta[property="og:description"]');

  if (description) description.content = copy.metaDescription;
  if (openGraphTitle) openGraphTitle.content = copy.metaTitle;
  if (openGraphDescription) openGraphDescription.content = copy.metaDescription;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = copy[element.dataset.i18n];
    if (value) element.textContent = value;
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const value = copy[element.dataset.i18nAriaLabel];
    if (value) element.setAttribute("aria-label", value);
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const value = copy[element.dataset.i18nAlt];
    if (value) element.setAttribute("alt", value);
  });

  const nextLanguageIsEnglish = language === "zh";
  languageToggle.textContent = nextLanguageIsEnglish ? "EN" : "中文";
  languageToggle.setAttribute(
    "aria-label",
    nextLanguageIsEnglish ? "切换为英文" : "Switch to Chinese"
  );
  languageToggle.setAttribute(
    "title",
    nextLanguageIsEnglish ? "切换为英文" : "Switch to Chinese"
  );

  saveLanguage(language);
}

let currentLanguage = readSavedLanguage();
applyLanguage(currentLanguage);

languageToggle.addEventListener("click", () => {
  currentLanguage = currentLanguage === "zh" ? "en" : "zh";
  applyLanguage(currentLanguage);
});
